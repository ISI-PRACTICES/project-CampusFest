CREATE TABLE IF NOT EXISTS EVENTO (
    ID VARCHAR(100) PRIMARY KEY,
    NOMBRE VARCHAR(255) NOT NULL,
    FECHA TIMESTAMP NOT NULL,
    LUGAR VARCHAR(255) NOT NULL,
    AFORO INT NOT NULL,
    BLOQUEADOS INT NOT NULL
);

CREATE TABLE IF NOT EXISTS RESERVA (
    CODIGO VARCHAR(100) PRIMARY KEY,
    EVENTO_ID VARCHAR(100) NOT NULL,
    ESTUDIANTE_ID VARCHAR(100) NOT NULL,
    VENCE_EN TIMESTAMP NOT NULL,
    ESTADO VARCHAR(20) NOT NULL,

    CONSTRAINT FK_RESERVA_EVENTO
        FOREIGN KEY (EVENTO_ID)
        REFERENCES EVENTO(ID)
);

CREATE TABLE IF NOT EXISTS ASISTENCIA (
    RESERVA_CODIGO VARCHAR(100) PRIMARY KEY,
    HORA TIMESTAMP NOT NULL,

    CONSTRAINT FK_ASISTENCIA_RESERVA
        FOREIGN KEY (RESERVA_CODIGO)
        REFERENCES RESERVA(CODIGO)
);
